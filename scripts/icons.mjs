// Regenerates src/components/icons.tsx from the MingCute icon set, fetched with better-icons
// (https://github.com/better-auth/better-icons). To add an icon: add a line to ICONS, run `npm run icons`.
import { execSync } from "node:child_process"
import { writeFileSync } from "node:fs"

const ICONS = {
  NotebookIcon: "notebook-2-line",
  ChartIcon: "chart-bar-line",
  LeftIcon: "left-line",
  RightIcon: "right-line",
  DownIcon: "down-line",
  MoreIcon: "more-1-line",
  ReturnIcon: "corner-down-left-line",
  AlertIcon: "alert-line",
  BulbIcon: "bulb-line",
  CheckCircleIcon: "check-circle-line",
  ArrowRightIcon: "arrow-right-line",
  TrendUpIcon: "trending-up-line",
  TrendDownIcon: "trending-down-line",
  DownloadIcon: "download-2-line",
  UploadIcon: "upload-2-line",
  WalletIcon: "wallet-4-line",
  RefreshIcon: "refresh-2-line",
  ThumbUpIcon: "thumb-up-2-line",
  ThumbDownIcon: "thumb-down-2-line",
  PencilIcon: "pencil-line",
  PiggyIcon: "pig-money-line",
  TargetIcon: "target-line",
  PhoneIcon: "cellphone-line",
  ShareIcon: "share-3-line",
  AddSquareIcon: "add-square-line",
  RepeatIcon: "repeat-line",
  CalendarIcon: "calendar-line",
  CheckIcon: "check-line",
  QuestionIcon: "question-line",
}

let out = `// Generated by scripts/icons.mjs from the MingCute set (via better-icons). Don't edit by hand:
// add the icon to the list there and run \`npm run icons\`. The SVG bodies are fixed strings from the icon set,
// never user input, so injecting them as HTML is safe.
import type { SVGProps } from "react"

const icon = (body: string) =>
  function Icon(props: SVGProps<SVGSVGElement>) {
    return <svg viewBox="0 0 24 24" width="1em" height="1em" aria-hidden="true" {...props} dangerouslySetInnerHTML={{ __html: body }} />
  }

`
for (const [name, id] of Object.entries(ICONS)) {
  const { svg, width, height } = JSON.parse(execSync(`npx --yes better-icons get mingcute:${id} --json`, { encoding: "utf8" }))
  if (width !== 24 || height !== 24) throw new Error(`${id} is ${width}x${height}; icons.tsx assumes a 24x24 grid`)
  out += `export const ${name} = icon(${JSON.stringify(svg.replace(/^<svg[^>]*>|<\/svg>$/g, ""))})\n`
  console.log("fetched", id)
}
writeFileSync(new URL("../src/components/icons.tsx", import.meta.url), out)
